-- Supabase setup for Mithun Mutsuddi portfolio reviews (v2026-11)
-- Run in Supabase → SQL Editor

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 80),
  company text check (char_length(company) <= 100),
  rating int not null check (rating between 1 and 5),
  comment text not null check (char_length(comment) <= 600),
  lang text default 'en',
  ip_hash text,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;

-- Public visitors may only read approved reviews
drop policy if exists "public read approved" on public.reviews;
create policy "public read approved" on public.reviews
  for select using (approved = true);

create index if not exists reviews_approved_idx on public.reviews (approved, created_at desc);
